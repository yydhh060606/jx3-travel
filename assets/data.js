// 主定位：卡片小签、筛选角标都取它
function ROLE_OF(name) {
  const s = SCHOOLS[name];
  return (s && s.chi[0] && s.chi[0][1]) || '';
}
// 该门派能担任的全部定位（去重、保持心法顺序）
function ROLES_OF(name) {
  const s = SCHOOLS[name];
  if (!s) return [];
  const out = [];
  (s.chi || []).forEach(([, r]) => { if (r && out.indexOf(r) === -1) out.push(r); });
  return out;
}

